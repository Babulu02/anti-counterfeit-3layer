"""
ml/scan_risk/train.py
======================
Train the scan-risk model and evaluate across 5 seeds.
Save artefacts and thresholds to experiments/results/.

NOTE: ALL DATA IS SIMULATED.

Pipeline
--------
1. Load data/scans.csv (generated by simulate_scans.py).
2. Compute features (features.py) with zero label/future leakage.
3. Split by product_id into train / val / test (60/20/20).
   Held-out attack variant (G_stealth_clone) is routed EXCLUSIVELY to test_df.
   Training and validation never see a single instance of G_stealth_clone.
4. Models trained & compared across 5 seeds:
   (1) Fair Rule Baseline (incorporates speed, burst, NFC counter gap, and sold status)
   (2) IsolationForest (unsupervised on genuine train scans)
   (3) RandomForest (supervised)
5. Decision thresholds chosen on the VALIDATION SET ONLY.
6. Evaluate on the TEST SET across 5 seeds:
   - Precision, Recall, F1, ROC-AUC, FAR (genuine)
   - Per-attack-type breakdown
   - Held-out attack variant performance
7. Save:
   experiments/results/rf_model.joblib
   experiments/results/if_model.joblib
   experiments/results/thresholds.json
   experiments/results/metrics.json
   experiments/results/roc_curve.png
   experiments/results/feature_importance.png
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

import joblib
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from sklearn.ensemble import IsolationForest, RandomForestClassifier
from sklearn.metrics import f1_score, precision_score, recall_score, roc_auc_score, roc_curve

from ml.scan_risk.features import FEATURE_COLS, compute_features

RESULTS_DIR = ROOT / "experiments" / "results"
RESULTS_DIR.mkdir(parents=True, exist_ok=True)
DATA_FILE = ROOT / "data" / "scans.csv"

SEEDS = [42, 7, 13, 99, 256]
HELD_OUT_ATTACK = "G_stealth_clone"


# ── Fair Rule Baseline ────────────────────────────────────────────────────────

class FairRuleBaseline:
    """
    Domain heuristic baseline incorporating multi-channel signals:
      - speed_kmh > speed_thresh (impossible velocity)
      - scans_1h > burst_thresh (rapid barcode scanning)
      - nfc_counter_gap < 0 (NFC replay / counter rollback)
      - nfc_counter_gap > gap_thresh (NFC counter skip / clone-first)
      - (sold == 1 and is_new_city == 1) (geographical displacement after sale)

    Thresholds are selected on the VALIDATION set only.
    """
    def __init__(self):
        self.speed_thresh = 900.0
        self.burst_thresh = 4
        self.gap_thresh = 5

    def fit_val(self, X_val: pd.DataFrame, y_val: np.ndarray):
        best_f1 = -1.0
        best_st = 900.0
        best_bt = 4
        best_gt = 5

        for st in [500.0, 750.0, 900.0, 1200.0]:
            for bt in [3, 4, 6, 8]:
                for gt in [3, 5, 8]:
                    preds = self._predict_with(X_val, st, bt, gt)
                    f1 = f1_score(y_val, preds, zero_division=0)
                    if f1 > best_f1:
                        best_f1 = f1
                        best_st = st
                        best_bt = bt
                        best_gt = gt

        self.speed_thresh = best_st
        self.burst_thresh = best_bt
        self.gap_thresh = best_gt

    def _predict_with(self, X: pd.DataFrame, st: float, bt: int, gt: int) -> np.ndarray:
        speed_flag = X["speed_kmh"] > st
        burst_flag = X["scans_1h"] > bt
        nfc_replay = (X["channel_nfc"] == 1) & (X["nfc_counter_gap"] < 0)
        nfc_jump = (X["channel_nfc"] == 1) & (X["nfc_counter_gap"] > gt)
        sold_reloc = (X["sold"] == 1) & (X["is_new_city"] == 1) & (X["dist_km"] > 300)

        flagged = speed_flag | burst_flag | nfc_replay | nfc_jump | sold_reloc
        return flagged.astype(int).values

    def predict(self, X: pd.DataFrame) -> np.ndarray:
        return self._predict_with(X, self.speed_thresh, self.burst_thresh, self.gap_thresh)

    def predict_proba_col(self, X: pd.DataFrame) -> np.ndarray:
        speed_norm = (X["speed_kmh"] / 1500.0).clip(0, 1)
        burst_norm = (X["scans_1h"] / 10.0).clip(0, 1)
        nfc_replay = ((X["channel_nfc"] == 1) & (X["nfc_counter_gap"] < 0)).astype(float)
        nfc_jump = np.where((X["channel_nfc"] == 1) & (X["nfc_counter_gap"] > 0),
                            (X["nfc_counter_gap"] / 15.0).clip(0, 1), 0.0)
        sold_reloc = ((X["sold"] == 1) & (X["is_new_city"] == 1) & (X["dist_km"] > 300)).astype(float) * 0.7

        scores = np.maximum.reduce([speed_norm.values, burst_norm.values, nfc_replay.values, nfc_jump, sold_reloc.values])
        return np.clip(scores, 0.0, 1.0)


# ── Split by Product with Held-Out Attack Isolation ──────────────────────────

def split_by_product_with_heldout(df: pd.DataFrame, train_ratio=0.60, val_ratio=0.20, seed=42):
    """
    Split products into train/val/test.
    Any product containing the held-out attack (HELD_OUT_ATTACK) is routed strictly to test_df.
    Remaining products are partitioned randomly by product_id.
    """
    all_pids = set(df["product_id"].unique())
    held_out_pids = set(df[df["attack_type"] == HELD_OUT_ATTACK]["product_id"].unique())
    eligible_pids = sorted(list(all_pids - held_out_pids))

    rng = np.random.default_rng(seed)
    rng.shuffle(eligible_pids)

    n = len(eligible_pids)
    t1 = int(n * train_ratio)
    t2 = int(n * (train_ratio + val_ratio))

    train_pids = set(eligible_pids[:t1])
    val_pids = set(eligible_pids[t1:t2])
    test_pids = set(eligible_pids[t2:]) | held_out_pids

    train_df = df[df["product_id"].isin(train_pids)].copy()
    val_df = df[df["product_id"].isin(val_pids)].copy()
    test_df = df[df["product_id"].isin(test_pids)].copy()

    return train_df, val_df, test_df


def _best_f1_threshold(scores: np.ndarray, labels: np.ndarray, candidates: np.ndarray) -> float:
    best_t, best_f1 = 0.5, -1.0
    for t in candidates:
        preds = (scores >= t).astype(int)
        f1 = f1_score(labels, preds, zero_division=0)
        if f1 > best_f1:
            best_f1, best_t = f1, float(t)
    return best_t


def _evaluate(name: str, labels: np.ndarray, preds: np.ndarray,
              scores: np.ndarray, attack_types: pd.Series) -> dict:
    genuine_mask = (labels == 0)
    far = float(preds[genuine_mask].mean()) if genuine_mask.sum() > 0 else 0.0

    try:
        auc = float(roc_auc_score(labels, scores))
    except Exception:
        auc = float("nan")

    prec = float(precision_score(labels, preds, zero_division=0))
    rec = float(recall_score(labels, preds, zero_division=0))
    f1 = float(f1_score(labels, preds, zero_division=0))

    result = {
        "model": name,
        "precision": prec,
        "recall": rec,
        "f1": f1,
        "roc_auc": auc,
        "false_alarm_rate_genuine": far,
        "per_attack_type": {},
    }

    clean_types = [str(x) for x in attack_types.unique() if pd.notna(x) and str(x).strip() != ""]
    for at in sorted(clean_types):
        mask = (attack_types.astype(str) == at).values
        if mask.sum() == 0:
            continue
        at_rec = float(recall_score(labels[mask], preds[mask], zero_division=0))
        at_prec = float(precision_score(labels[mask], preds[mask], zero_division=0))
        at_f1 = float(f1_score(labels[mask], preds[mask], zero_division=0))
        result["per_attack_type"][at] = {
            "recall": at_rec,
            "precision": at_prec,
            "f1": at_f1,
            "n": int(mask.sum()),
        }

    return result


# ── Run Evaluation Across 5 Seeds ────────────────────────────────────────────

def run_experiment_5_seeds():
    print("\nNOTE: ALL DATA IS SIMULATED")
    print(f"Loading data from {DATA_FILE}...")
    df = pd.read_csv(DATA_FILE, comment="#", encoding="utf-8")
    df["timestamp"] = pd.to_datetime(df["timestamp"], format="ISO8601")
    print(f"  Total scans: {len(df)}, products: {df['product_id'].nunique()}, attack rate: {df['label'].mean():.1%}")

    print("Computing features...")
    feats = compute_features(df)
    df_sorted = df.copy()
    df_sorted["timestamp"] = pd.to_datetime(df_sorted["timestamp"], format="ISO8601")
    df_sorted = df_sorted.sort_values(["product_id", "timestamp"]).reset_index(drop=True)
    feats = feats.reset_index(drop=True)
    assert len(feats) == len(df_sorted), "Length mismatch"
    feats["product_id"] = df_sorted["product_id"].values
    feats["label"] = df_sorted["label"].values
    feats["attack_type"] = df_sorted["attack_type"].fillna("").astype(str).values

    seed_metrics = {m: [] for m in ["rule_baseline", "isolation_forest", "random_forest"]}
    models_saved = {}
    thresholds_saved = {}
    test_eval_saved = {}

    for seed in SEEDS:
        train_df, val_df, test_df = split_by_product_with_heldout(feats, seed=seed)

        X_train = train_df[FEATURE_COLS]
        y_train = train_df["label"].values
        X_val = val_df[FEATURE_COLS]
        y_val = val_df["label"].values
        X_test = test_df[FEATURE_COLS]
        y_test = test_df["label"].values

        # 1. Fair Rule Baseline
        rule = FairRuleBaseline()
        rule.fit_val(X_val, y_val)
        rule_scores = rule.predict_proba_col(X_test)
        rule_preds = rule.predict(X_test)
        m_rule = _evaluate("rule_baseline", y_test, rule_preds, rule_scores, test_df["attack_type"])
        seed_metrics["rule_baseline"].append(m_rule)

        # 2. Isolation Forest
        iso = IsolationForest(n_estimators=150, contamination=0.20, random_state=seed, n_jobs=-1)
        iso.fit(X_train[y_train == 0])
        iso_val_scores = -iso.score_samples(X_val)
        candidates = np.percentile(iso_val_scores, np.linspace(40, 98, 50))
        iso_thresh = _best_f1_threshold(iso_val_scores, y_val, candidates)
        iso_test_scores = -iso.score_samples(X_test)
        iso_preds = (iso_test_scores >= iso_thresh).astype(int)
        m_iso = _evaluate("isolation_forest", y_test, iso_preds, iso_test_scores, test_df["attack_type"])
        seed_metrics["isolation_forest"].append(m_iso)

        # 3. Random Forest
        rf = RandomForestClassifier(n_estimators=200, max_depth=10, min_samples_leaf=2,
                                    class_weight="balanced", random_state=seed, n_jobs=-1)
        rf.fit(X_train, y_train)
        rf_val_proba = rf.predict_proba(X_val)[:, 1]
        rf_thresh = _best_f1_threshold(rf_val_proba, y_val, np.linspace(0.1, 0.9, 81))
        rf_test_proba = rf.predict_proba(X_test)[:, 1]
        rf_preds = (rf_test_proba >= rf_thresh).astype(int)
        m_rf = _evaluate("random_forest", y_test, rf_preds, rf_test_proba, test_df["attack_type"])
        seed_metrics["random_forest"].append(m_rf)

        # Keep artefacts from primary seed (42)
        if seed == 42:
            models_saved["rf"] = rf
            models_saved["iso"] = iso
            thresholds_saved["random_forest"] = float(rf_thresh)
            thresholds_saved["isolation_forest"] = float(iso_thresh)
            thresholds_saved["rule_speed_kmh"] = float(rule.speed_thresh)
            thresholds_saved["rule_burst_1h"] = int(rule.burst_thresh)
            thresholds_saved["rule_gap_thresh"] = int(rule.gap_thresh)

            test_eval_saved["y_test"] = y_test
            test_eval_saved["rule_scores"] = rule_scores
            test_eval_saved["iso_scores"] = iso_test_scores
            test_eval_saved["rf_scores"] = rf_test_proba
            test_eval_saved["rf_importances"] = rf.feature_importances_

    # Aggregate 5-seed statistics
    print("\n" + "=" * 80)
    print("5-SEED EVALUATION SUMMARY (mean +/- std)")
    print(f"Seeds: {SEEDS}")
    print(f"{'Model':<20} {'Precision':>14} {'Recall':>14} {'F1':>14} {'ROC-AUC':>14} {'FAR(genuine)':>16}")
    print("-" * 94)

    summary_stats = {}
    metric_keys = ["precision", "recall", "f1", "roc_auc", "false_alarm_rate_genuine"]

    for m_name in ["rule_baseline", "isolation_forest", "random_forest"]:
        runs = seed_metrics[m_name]
        stats = {}
        for k in metric_keys:
            vals = [r[k] for r in runs if not np.isnan(r[k])]
            mean_v = float(np.mean(vals)) if vals else 0.0
            std_v = float(np.std(vals)) if vals else 0.0
            stats[k] = {"mean": mean_v, "std": std_v}

        summary_stats[m_name] = stats
        p_str = f"{stats['precision']['mean']:.3f} +/- {stats['precision']['std']:.3f}"
        r_str = f"{stats['recall']['mean']:.3f} +/- {stats['recall']['std']:.3f}"
        f_str = f"{stats['f1']['mean']:.3f} +/- {stats['f1']['std']:.3f}"
        a_str = f"{stats['roc_auc']['mean']:.3f} +/- {stats['roc_auc']['std']:.3f}"
        far_str = f"{stats['false_alarm_rate_genuine']['mean']:.3f} +/- {stats['false_alarm_rate_genuine']['std']:.3f}"
        print(f"{m_name:<20} {p_str:>14} {r_str:>14} {f_str:>14} {a_str:>14} {far_str:>16}")

    # Per-attack-type breakdown (RandomForest)
    print("\nPer-Attack Breakdown for RandomForest (5-seed mean +/- std):")
    all_attack_types = set()
    for run in seed_metrics["random_forest"]:
        all_attack_types.update(run["per_attack_type"].keys())

    at_stats = {}
    for at in sorted(all_attack_types):
        f1_vals = [r["per_attack_type"][at]["f1"] for r in seed_metrics["random_forest"] if at in r["per_attack_type"]]
        rec_vals = [r["per_attack_type"][at]["recall"] for r in seed_metrics["random_forest"] if at in r["per_attack_type"]]
        prec_vals = [r["per_attack_type"][at]["precision"] for r in seed_metrics["random_forest"] if at in r["per_attack_type"]]
        at_stats[at] = {
            "f1": {"mean": float(np.mean(f1_vals)), "std": float(np.std(f1_vals))},
            "recall": {"mean": float(np.mean(rec_vals)), "std": float(np.std(rec_vals))},
            "precision": {"mean": float(np.mean(prec_vals)), "std": float(np.std(prec_vals))},
        }
        note = " [HELD-OUT TEST ONLY]" if at == HELD_OUT_ATTACK else ""
        print(f"  {at + note:<35} F1={np.mean(f1_vals):.3f} +/- {np.std(f1_vals):.3f}  Recall={np.mean(rec_vals):.3f} +/- {np.std(rec_vals):.3f}")

    # Save artefacts from primary seed
    print("\nSaving model artefacts and thresholds...")
    joblib.dump(models_saved["rf"], RESULTS_DIR / "rf_model.joblib")
    joblib.dump(models_saved["iso"], RESULTS_DIR / "if_model.joblib")

    with open(RESULTS_DIR / "thresholds.json", "w", encoding="utf-8") as f:
        json.dump(thresholds_saved, f, indent=2)

    metrics_payload = {
        "note": "ALL DATA IS SIMULATED. 5 seeds evaluated.",
        "seeds": SEEDS,
        "summary": summary_stats,
        "per_attack_type": at_stats,
        "held_out_attack": HELD_OUT_ATTACK,
        "thresholds": thresholds_saved,
    }
    with open(RESULTS_DIR / "metrics.json", "w", encoding="utf-8") as f:
        json.dump(metrics_payload, f, indent=2)

    # ROC curve plot
    fig, ax = plt.subplots(figsize=(7, 5))
    y_test = test_eval_saved["y_test"]
    for name, scores in [
        ("Fair Rule Baseline", test_eval_saved["rule_scores"]),
        ("IsolationForest", test_eval_saved["iso_scores"]),
        ("RandomForest", test_eval_saved["rf_scores"]),
    ]:
        fpr, tpr, _ = roc_curve(y_test, scores)
        auc = roc_auc_score(y_test, scores)
        ax.plot(fpr, tpr, label=f"{name} (AUC={auc:.3f})")

    ax.plot([0, 1], [0, 1], "k--", linewidth=0.8)
    ax.set_xlabel("False Positive Rate")
    ax.set_ylabel("True Positive Rate")
    ax.set_title("ROC Curves (5-Seed Simulation, Seed 42)")
    ax.legend()
    ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(RESULTS_DIR / "roc_curve.png", dpi=120)
    plt.close(fig)

    # Feature importance plot
    fi = pd.Series(test_eval_saved["rf_importances"], index=FEATURE_COLS).sort_values()
    fig2, ax2 = plt.subplots(figsize=(7, 5))
    fi.plot.barh(ax=ax2, color="steelblue")
    ax2.set_title("RandomForest Feature Importances (MDI)")
    ax2.set_xlabel("Mean Decrease in Impurity")
    fig2.tight_layout()
    fig2.savefig(RESULTS_DIR / "feature_importance.png", dpi=120)
    plt.close(fig2)

    print(f"Artefacts written to {RESULTS_DIR}/")
    print("  rf_model.joblib, if_model.joblib, thresholds.json,")
    print("  metrics.json, roc_curve.png, feature_importance.png")
    return metrics_payload


if __name__ == "__main__":
    run_experiment_5_seeds()
