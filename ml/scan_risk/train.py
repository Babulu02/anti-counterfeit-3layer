"""
ml/scan_risk/train.py
======================
Train the scan-risk model and save artefacts to /experiments/results/.

⚠️  ALL DATA IS SIMULATED.  See simulate_scans.py.

Pipeline
--------
1. Load /data/scans.csv (generated by simulate_scans.py).
2. Compute features (features.py).
3. Split by product_id into train / val / test (60/20/20).
   NEVER split by row — that leaks future scans into training.
4. Train three models:
   (1) Rule baseline  — speed_kmh > threshold OR scans_1h > threshold
   (2) IsolationForest (unsupervised)
   (3) RandomForest    (supervised)
5. Choose decision thresholds on the VALIDATION SET ONLY.
6. Evaluate on the TEST SET and report:
   precision, recall, F1, ROC-AUC, false-alarm rate on genuine scans —
   overall and per attack type.
7. Save:
   experiments/results/rf_model.joblib
   experiments/results/if_model.joblib
   experiments/results/thresholds.json
   experiments/results/metrics.json
   experiments/results/roc_curve.png
   experiments/results/feature_importance.png

Run from repo root (venv active):
    python ml/scan_risk/train.py
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

import joblib
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")   # non-interactive backend — no display needed
import matplotlib.pyplot as plt

from sklearn.ensemble import IsolationForest, RandomForestClassifier
from sklearn.metrics import (
    classification_report, f1_score, precision_score,
    recall_score, roc_auc_score, roc_curve,
)
from sklearn.preprocessing import label_binarize

from ml.scan_risk.features import FEATURE_COLS, compute_features

RESULTS_DIR = ROOT / "experiments" / "results"
RESULTS_DIR.mkdir(parents=True, exist_ok=True)
DATA_FILE   = ROOT / "data" / "scans.csv"


# ── Data loading ──────────────────────────────────────────────────────────────

def load_data() -> pd.DataFrame:
    """Load scans.csv, skipping the comment header line."""
    df = pd.read_csv(DATA_FILE, comment="#", encoding="utf-8")
    df["timestamp"] = pd.to_datetime(df["timestamp"])
    return df


# ── Split by product_id ───────────────────────────────────────────────────────

def split_by_product(df: pd.DataFrame, train=0.60, val=0.20, seed=42):
    """
    Split the unique product_ids into train/val/test sets (60/20/20).
    All scans for a product stay together in one split — no row-level leakage.
    """
    pids = sorted(df["product_id"].unique())
    rng  = np.random.default_rng(seed)
    rng.shuffle(pids)
    n    = len(pids)
    t1   = int(n * train)
    t2   = int(n * (train + val))
    return (
        df[df["product_id"].isin(pids[:t1])].copy(),
        df[df["product_id"].isin(pids[t1:t2])].copy(),
        df[df["product_id"].isin(pids[t2:])].copy(),
    )


# ── Threshold selection on validation set ─────────────────────────────────────

def _best_f1_threshold(scores: np.ndarray, labels: np.ndarray,
                       candidates: np.ndarray) -> float:
    """Return the threshold from candidates that maximises F1 on (scores, labels)."""
    best_t, best_f1 = 0.5, -1.0
    for t in candidates:
        preds = (scores >= t).astype(int)
        f1    = f1_score(labels, preds, zero_division=0)
        if f1 > best_f1:
            best_f1, best_t = f1, float(t)
    return best_t


# ── Evaluation ────────────────────────────────────────────────────────────────

def _evaluate(name: str, labels: np.ndarray, preds: np.ndarray,
              scores: np.ndarray, attack_types: pd.Series) -> dict:
    """Return a metrics dict for one model on one split."""
    genuine_mask = labels == 0
    far          = float(preds[genuine_mask].mean()) if genuine_mask.sum() > 0 else 0.0

    try:
        auc = float(roc_auc_score(labels, scores))
    except Exception:
        auc = float("nan")

    result = {
        "model":        name,
        "precision":    float(precision_score(labels, preds, zero_division=0)),
        "recall":       float(recall_score(labels, preds, zero_division=0)),
        "f1":           float(f1_score(labels, preds, zero_division=0)),
        "roc_auc":      auc,
        "false_alarm_rate_genuine": far,
        "per_attack_type": {},
    }

    # Per attack type
    for at in attack_types.unique():
        if not at:
            continue
        mask = (attack_types == at).values
        if mask.sum() == 0:
            continue
        result["per_attack_type"][at] = {
            "recall":    float(recall_score(labels[mask], preds[mask], zero_division=0)),
            "precision": float(precision_score(labels[mask], preds[mask], zero_division=0)),
            "f1":        float(f1_score(labels[mask], preds[mask], zero_division=0)),
            "n":         int(mask.sum()),
        }
    return result


# ── Rule baseline ──────────────────────────────────────────────────────────────

class RuleBaseline:
    """
    Simple threshold rules:
      score = 1 if speed_kmh > speed_thresh OR scans_1h > burst_thresh
    Thresholds are chosen to maximise F1 on the validation set.
    """
    def __init__(self):
        self.speed_thresh = 900.0
        self.burst_thresh = 5

    def fit_val(self, X_val: pd.DataFrame, y_val: np.ndarray):
        best_f1 = -1.0
        for st in [500, 700, 900, 1100, 1400]:
            for bt in [3, 5, 7, 10]:
                preds = self._predict_with(X_val, st, bt)
                f1    = f1_score(y_val, preds, zero_division=0)
                if f1 > best_f1:
                    best_f1           = f1
                    self.speed_thresh = st
                    self.burst_thresh = bt

    def _predict_with(self, X, st, bt):
        return ((X["speed_kmh"] > st) | (X["scans_1h"] > bt)).astype(int).values

    def predict(self, X: pd.DataFrame) -> np.ndarray:
        return self._predict_with(X, self.speed_thresh, self.burst_thresh)

    def predict_proba_col(self, X: pd.DataFrame) -> np.ndarray:
        """Return a float score in [0,1] for ROC-AUC computation."""
        speed_norm = (X["speed_kmh"] / 2000.0).clip(0, 1)
        burst_norm = (X["scans_1h"] / 15.0).clip(0, 1)
        return np.maximum(speed_norm.values, burst_norm.values)


# ── Main training pipeline ─────────────────────────────────────────────────────

def train():
    print("\nNOTE: ALL DATA IS SIMULATED")
    print("Loading data...")
    df = load_data()
    print(f"  Total rows: {len(df)},  products: {df['product_id'].nunique()}")
    print(f"  Attack rate: {df['label'].mean():.1%}")

    print("Computing features...")
    feats = compute_features(df)
    # Align labels and attack_type back (feats may be reordered by product/time)
    # We re-sort df the same way features.py does internally
    df_sorted = df.copy()
    df_sorted["timestamp"] = pd.to_datetime(df_sorted["timestamp"])
    df_sorted = df_sorted.sort_values(["product_id", "timestamp"]).reset_index(drop=True)
    feats = feats.reset_index(drop=True)
    assert len(feats) == len(df_sorted), "Feature/label length mismatch"
    feats["product_id"]  = df_sorted["product_id"].values
    feats["label"]       = df_sorted["label"].values
    feats["attack_type"] = df_sorted["attack_type"].values

    print("Splitting by product_id (60/20/20)...")
    train_df, val_df, test_df = split_by_product(feats)
    print(f"  Train: {len(train_df)} rows ({train_df['product_id'].nunique()} products)")
    print(f"  Val:   {len(val_df)}  rows ({val_df['product_id'].nunique()} products)")
    print(f"  Test:  {len(test_df)} rows ({test_df['product_id'].nunique()} products)")

    X_train = train_df[FEATURE_COLS]
    y_train = train_df["label"].values
    X_val   = val_df[FEATURE_COLS]
    y_val   = val_df["label"].values
    X_test  = test_df[FEATURE_COLS]
    y_test  = test_df["label"].values

    all_metrics = {}

    # ── 1. Rule baseline ──────────────────────────────────────────────────────
    print("\nTraining rule baseline...")
    rule = RuleBaseline()
    rule.fit_val(X_val, y_val)
    print(f"  speed_thresh={rule.speed_thresh}, burst_thresh={rule.burst_thresh}")
    rule_scores  = rule.predict_proba_col(X_test)
    rule_preds   = rule.predict(X_test)
    all_metrics["rule_baseline"] = _evaluate(
        "rule_baseline", y_test, rule_preds, rule_scores,
        test_df["attack_type"]
    )

    # ── 2. IsolationForest ────────────────────────────────────────────────────
    print("Training IsolationForest...")
    iso = IsolationForest(n_estimators=200, contamination=0.3,
                           random_state=42, n_jobs=-1)
    iso.fit(X_train[y_train == 0])   # fit on genuine only (unsupervised)

    # Threshold on validation: iso.score_samples returns negative (more negative = more anomalous)
    iso_val_scores = -iso.score_samples(X_val)   # flip so higher = more anomalous
    candidates     = np.percentile(iso_val_scores, np.linspace(50, 99, 50))
    iso_thresh     = _best_f1_threshold(iso_val_scores, y_val, candidates)
    iso_test_scores = -iso.score_samples(X_test)
    iso_preds       = (iso_test_scores >= iso_thresh).astype(int)
    all_metrics["isolation_forest"] = _evaluate(
        "isolation_forest", y_test, iso_preds, iso_test_scores,
        test_df["attack_type"]
    )
    print(f"  IsolationForest threshold={iso_thresh:.4f}")

    # ── 3. RandomForest ───────────────────────────────────────────────────────
    print("Training RandomForest...")
    rf = RandomForestClassifier(n_estimators=200, max_depth=12,
                                 class_weight="balanced",
                                 random_state=42, n_jobs=-1)
    rf.fit(X_train, y_train)
    rf_val_proba   = rf.predict_proba(X_val)[:, 1]
    rf_thresh      = _best_f1_threshold(rf_val_proba, y_val,
                                         np.linspace(0.1, 0.9, 81))
    rf_test_proba  = rf.predict_proba(X_test)[:, 1]
    rf_preds       = (rf_test_proba >= rf_thresh).astype(int)
    all_metrics["random_forest"] = _evaluate(
        "random_forest", y_test, rf_preds, rf_test_proba,
        test_df["attack_type"]
    )
    print(f"  RandomForest threshold={rf_thresh:.4f}")

    # ── Print summary ─────────────────────────────────────────────────────────
    print("\n-- Test-set metrics (NOTE: simulated data) --")
    print(f"{'Model':<20} {'Precision':>10} {'Recall':>8} {'F1':>8} {'ROC-AUC':>10} {'FAR(genuine)':>14}")
    print("-" * 72)
    for name, m in all_metrics.items():
        print(f"{name:<20} {m['precision']:>10.3f} {m['recall']:>8.3f} "
              f"{m['f1']:>8.3f} {m['roc_auc']:>10.3f} "
              f"{m['false_alarm_rate_genuine']:>14.3f}")

    print("\nPer-attack-type F1 (RandomForest):")
    for at, v in sorted(all_metrics["random_forest"]["per_attack_type"].items()):
        print(f"  {at:<30}  F1={v['f1']:.3f}  recall={v['recall']:.3f}  n={v['n']}")

    # ── Save artefacts ────────────────────────────────────────────────────────
    print("\nSaving artefacts...")
    joblib.dump(rf,  RESULTS_DIR / "rf_model.joblib")
    joblib.dump(iso, RESULTS_DIR / "if_model.joblib")

    thresholds = {
        "random_forest":    rf_thresh,
        "isolation_forest": float(iso_thresh),
        "rule_speed_kmh":   rule.speed_thresh,
        "rule_burst_1h":    rule.burst_thresh,
    }
    with open(RESULTS_DIR / "thresholds.json", "w") as f:
        json.dump(thresholds, f, indent=2)

    metrics_out = {
        "note": "ALL DATA IS SIMULATED",
        "models": all_metrics,
        "thresholds": thresholds,
    }
    with open(RESULTS_DIR / "metrics.json", "w") as f:
        json.dump(metrics_out, f, indent=2)

    # ── ROC curve plot ────────────────────────────────────────────────────────
    fig, ax = plt.subplots(figsize=(7, 5))
    for name, scores in [
        ("Rule baseline",    rule_scores),
        ("IsolationForest",  iso_test_scores),
        ("RandomForest",     rf_test_proba),
    ]:
        try:
            fpr, tpr, _ = roc_curve(y_test, scores)
            auc          = roc_auc_score(y_test, scores)
            ax.plot(fpr, tpr, label=f"{name} (AUC={auc:.3f})")
        except Exception:
            pass
    ax.plot([0,1],[0,1],"k--", linewidth=0.8)
    ax.set_xlabel("False Positive Rate"); ax.set_ylabel("True Positive Rate")
    ax.set_title("ROC curves (NOTE: simulated data)")
    ax.legend(); ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(RESULTS_DIR / "roc_curve.png", dpi=120)
    plt.close(fig)

    # ── Feature importance plot ───────────────────────────────────────────────
    fi   = pd.Series(rf.feature_importances_, index=FEATURE_COLS).sort_values()
    fig2, ax2 = plt.subplots(figsize=(7, 5))
    fi.plot.barh(ax=ax2, color="steelblue")
    ax2.set_title("RandomForest feature importances")
    ax2.set_xlabel("Mean decrease in impurity")
    fig2.tight_layout()
    fig2.savefig(RESULTS_DIR / "feature_importance.png", dpi=120)
    plt.close(fig2)

    print(f"Artefacts written to {RESULTS_DIR}/")
    print("  rf_model.joblib, if_model.joblib, thresholds.json,")
    print("  metrics.json, roc_curve.png, feature_importance.png")
    return all_metrics


if __name__ == "__main__":
    train()
